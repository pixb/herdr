#!/usr/bin/env python3
"""Regenerate THIRD-PARTY-NOTICES.md from Cargo.lock and the in-tree license files.

A distribution of this tree ships the root Apache-2.0 license plus the licenses
below. Cargo.lock carries no license metadata, so the crate table records the
exact name, version, and source that a binary embeds; the license text of each
crate is published with that crate by its registry page.
"""
from __future__ import annotations

import datetime
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "THIRD-PARTY-NOTICES.md"

IN_TREE = [
    ("vendored libghostty-vt", "vendor/libghostty-vt/LICENSE"),
    ("vendored portable-pty", "vendor/portable-pty/LICENSE.md"),
    ("Windows ConPTY runtime (Windows packaging)", "packaging/windows/licenses/Microsoft.Windows.Console.ConPTY-LICENSE.txt"),
    ("Windows ConPTY runtime notice (Windows packaging)", "packaging/windows/licenses/Microsoft.Windows.Console.ConPTY-NOTICE.md"),
]


def cargo_packages() -> list[dict[str, str]]:
    lock = (ROOT / "Cargo.lock").read_text()
    packages: list[dict[str, str]] = []
    for block in lock.split("[[package]]")[1:]:
        entry: dict[str, str] = {}
        for key in ("name", "version", "source"):
            match = re.search(rf'^{key} = "([^"]*)"', block, re.MULTILINE)
            if match:
                entry[key] = match.group(1)
        if "name" in entry:
            packages.append(entry)
    return packages


def main() -> None:
    packages = sorted(
        (p for p in cargo_packages() if "registry+" in p.get("source", "")),
        key=lambda p: p["name"].lower(),
    )
    workspace = sorted(p["name"] for p in cargo_packages() if "source" not in p)
    today = datetime.date.today().isoformat()

    lines: list[str] = []
    lines.append("# Third-party notices")
    lines.append("")
    lines.append(f"Generated by `scripts/fork/third_party_notices.py` on {today}. Regenerate it after any dependency change.")
    lines.append("")
    lines.append("Distributing this tree requires the root `LICENSE` (Apache-2.0), the modification notice in `CHANGES`, and everything in this file.")
    lines.append("")
    lines.append("## In-tree license texts")
    lines.append("")
    for label, rel in IN_TREE:
        path = ROOT / rel
        if not path.exists():
            continue
        text = path.read_text().strip()
        lines.append(f"### {label}")
        lines.append("")
        lines.append(f"Source file: `{rel}`")
        lines.append("")
        lines.append("```text")
        lines.append(text)
        lines.append("```")
        lines.append("")
    lines.append("## Crates embedded in the binary")
    lines.append("")
    lines.append(f"{len(packages)} crates from the crates.io registry, plus the workspace members {', '.join(workspace)}.")
    lines.append("")
    lines.append("| crate | version | source |")
    lines.append("|---|---|---|")
    for pkg in packages:
        source = pkg.get("source", "").replace("registry+https://github.com/rust-lang/crates.io-index", "crates.io")
        lines.append(f"| {pkg['name']} | {pkg['version']} | {source} |")
    lines.append("")
    lines.append("Each crate's own license text ships with that crate in its published package and on its registry page. The vendored sources under `vendor/` keep their upstream notices in place.")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{OUT.name}: {len(packages)} registry crates, {len(workspace)} workspace members, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
